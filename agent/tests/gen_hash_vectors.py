"""Regenerate agent/tests/fixtures/hash_vectors.json from src/filecat/hashing.py, the reference.

    PYTHONPATH=src python agent/tests/gen_hash_vectors.py

The test files are generated, not stored: block k (1 MiB) byte i is (i + (i >> 12) * 7 + k * 13)
& 0xff, as `pattern_block` in agent/src/prims.rs. Each case lists, per hash policy, the digest
hashing.hash_file returns for the 100 ns-floored mtime.
"""
import json
import os
import tempfile
from pathlib import Path

from filecat.hashing import hash_file

MIB = 1024 * 1024
OUT = Path(__file__).parent / "fixtures" / "hash_vectors.json"
CASES = [  # (size, mtime_ns)
    (0, 1761001200000000000),
    (1, 1761001200123456789),
    (11, 0),
    (MIB, 1761001200123456789),
    (64 * MIB, 1761001200123456789),            # the cutoff: still a whole-file digest
    (64 * MIB + 1, 1761001200123456789),        # first size that is partial
    (64 * MIB + 1, 1761001200123456701),        # same file, mtime differing only below 100 ns: same digest
    (64 * MIB + 3 * MIB + 777, -1234567891),    # negative mtime, odd size
]


def block(k: int) -> bytes:
    base = bytes((i + (i >> 12) * 7) & 0xFF for i in range(MIB))
    table = bytes((b + k * 13) & 0xFF for b in range(256))
    return base.translate(table)


def main() -> None:
    cache: dict[int, bytes] = {}
    cases = []
    with tempfile.TemporaryDirectory() as tmp:
        for size, mtime in CASES:
            path = os.path.join(tmp, f"f{size}")
            with open(path, "wb") as f:
                left, k = size, 0
                while left > 0:
                    blk = cache.setdefault(k, block(k))
                    n = min(left, MIB)
                    f.write(blk[:n])
                    left -= n
                    k += 1
            floored = mtime - mtime % 100
            cases.append({"size": size, "mtime_ns": mtime,
                          "expect": {p: hash_file(path, size, floored, p) for p in ("auto", "full", "none")}})
            os.unlink(path)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"about": "generated by gen_hash_vectors.py from src/filecat/hashing.py", "cases": cases}, indent=1) + "\n",
                   newline="\n")
    print(f"wrote {OUT} ({len(cases)} cases)")


if __name__ == "__main__":
    main()
